"""Checks for the repo-check scripts in scripts/.

Run: python3 scripts/tests/test_repo_checks.py   (or pytest scripts/tests)
"""
import contextlib
import io
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from check_commit_msg import problems  # noqa: E402  (path set up above)
from check_osv_report import findings, main  # noqa: E402
from check_tracked_files import violations  # noqa: E402

AI = "Cl" + "aude"  # kept out of the literal so a name scan of this file stays clean


def test_commit_msg():
    assert problems(["feat(sim): add supply decay (NX-123)"]) == []
    assert problems(["fix!: drop legacy frame", "", "body"]) == []
    assert problems(["docs: regenerate types", "", "Generated by datamodel-codegen"]) == []
    assert problems(["Merge branch 'develop'"]) == []
    assert problems(["Revert \"feat(sim): x\""]) == []
    assert problems(["# only a comment", ""]) == ["commit message is empty"]
    assert len(problems(["added stuff"])) == 1
    assert len(problems(["feat: x", "", f"Co-Authored-By: {AI} <noreply@example.com>"])) == 1
    assert len(problems(["feat: x", "", f"Generated with [{AI} Code](https://example.com)"])) == 1
    assert problems(["feat: x", "", "Co-Authored-By: Sam Lee <sam@example.com>"]) == []


def test_tracked_files():
    sizes = {"docs/a.md": 10, "big.png": 6 * 1024 * 1024}
    bad = violations(
        tracked=["docs/a.md", "clips/raid.mp4", "nexus.db", "services/sim/data/x.json", "docs/ops/data/c.csv",
                 "services/sim/src/nexus/clips/__init__.py", "big.png", "gone.txt"],
        ignored=["notes.log"],
        size_of=sizes.get,
    )
    assert sorted(p for p, _ in bad) == ["big.png", "clips/raid.mp4", "nexus.db", "notes.log",
                                          "services/sim/data/x.json"]


def test_osv_report():
    def pkg(name, groups, fixed_ids, version="1.0.0", fixed="9", fix_pkg=None):
        affected = [{"package": {"ecosystem": "PyPI", "name": fix_pkg or name},
                     "ranges": [{"events": [{"introduced": "0"}, {"fixed": fixed}]}]}]
        vulns = [{"id": i, "affected": affected} for i in fixed_ids]
        return {"package": {"ecosystem": "PyPI", "name": name, "version": version}, "groups": groups,
                "vulnerabilities": vulns}
    report = {"results": [{"packages": [
        pkg("a", [{"ids": ["V1", "G1"], "max_severity": "7.0"}], ["G1"]),   # high + fix: blocks
        pkg("b", [{"ids": ["V2"], "max_severity": "9.8"}], []),             # critical, no fix: listed only
        pkg("c", [{"ids": ["V3"], "max_severity": "6.9"}], ["V3"]),         # medium: listed only
        pkg("d", [{"ids": ["V4"], "max_severity": ""}], ["V4"]),            # no score: listed only
        pkg("e", [{"ids": ["V5"], "max_severity": "8"}], ["V5"], fix_pkg="other"),         # fix is another pkg's
        pkg("Typing_Ext", [{"ids": ["V6"], "max_severity": "8"}], ["V6"], fix_pkg="typing-ext"),  # PEP 503 name
        pkg("g", [{"ids": ["V7"], "max_severity": "8"}], ["V7"], version="2.0.0", fixed="1.2.5"),  # fix is older
        pkg("h", [{"ids": ["V8"], "max_severity": "8"}], ["V8"], version="2.0.0", fixed="2.0.1"),  # fix is newer
        pkg("i", [{"ids": ["V9"], "max_severity": "9.0"}], ["V9"]),         # critical + fix: blocks on every branch
    ]}]}
    assert [b for b, _ in findings(report)] == [True, False, False, False, False, True, False, True, True]
    # develop threshold (CVSS 9.0, ADR-0009 amendment): only the critical one with a fix blocks
    assert [b for b, _ in findings(report, 9.0)] == [False] * 8 + [True]
    assert findings({"results": []}) == []
    # A newline in a PR-controlled package name must not let a line start with "::" (workflow command).
    evil = {"results": [{"packages": [pkg("x\n::error::pwned\r", [{"ids": ["V9"], "max_severity": "5"}], [])]}]}
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(evil, f)
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        assert main(["check_osv_report.py", f.name]) == 0
    os.unlink(f.name)
    assert not any(line.startswith("::") for line in out.getvalue().splitlines())
    assert "\r" not in out.getvalue()

if __name__ == "__main__":
    test_commit_msg()
    test_tracked_files()
    test_osv_report()
    print("ok")
